#!/usr/bin/env python3
"""Generates llms-full.txt — the whole document set in one fetch.

Run from anywhere: python3 admin/build/gen_llms_full.py

Why this file exists: an agent consuming the parent site's documentation reported
that the index fetch worked and then link-following failed, because agent fetch
tools frequently refuse URLs a search has not already returned. Its conclusion was
that llms.txt is not a convenience for such agents but the whole surface, and its
second recommendation was a single-file concatenation so that one fetch gets
everything.

This concatenates llms.txt, the front page's markdown twin, and every source
document under briefs/ in reading order. It does NOT include the prose of the
rendered HTML pages — that is the remaining half, and it is task T5 on the comms
board rather than a silent omission.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VERSION = (ROOT / "admin/build/version.txt").read_text().strip()
PACK = "v0.33.62__nfrs-brief-pack__"

ORDER = ["README", "00__BRIEF", "01__the-topic-map", "02__the-memory-thesis",
         "03__the-owned-disciplines", "04__site-architecture",
         "05__boundaries-and-licensing", "06__gaps-and-open-questions", "LICENCE"]

HEADER = f"""# nfrs.sgit.ai — everything, in one file

Site version: {VERSION}. Generated by admin/build/gen_llms_full.py — do not edit by hand.

This is /llms.txt, then the front page, then all nine source documents, concatenated in
reading order. It exists because agent fetch tools frequently refuse URLs a search has not
already returned, which makes link-following unreliable and makes a single-file surface the
practical one. If you can make more than one request, prefer the individual documents at
https://nfrs.sgit.ai/briefs/<filename> — they are the source of truth and this file is a
concatenation of them.

One document from the source pack is deliberately absent: the source manifest, which
indexes do-not-publish material by repository path. The boundaries it defines are stated
in full at https://nfrs.sgit.ai/shipped/index.html#boundaries.

All content is released under the Creative Commons Attribution 4.0 International licence
(CC BY 4.0). Third-party material quoted inside these documents stays under its own terms.

Contents, in order:
  1. llms.txt — the annotated map, each entry carrying its page's single most important fact
  2. index.md — the front page as markdown
  3-11. the source documents, verbatim

"""

SEP = "\n\n" + "=" * 78 + "\n== {name}\n" + "=" * 78 + "\n\n"


def main():
    parts = [HEADER, SEP.format(name="llms.txt"), (ROOT / "llms.txt").read_text(),
             SEP.format(name="index.md — the front page"), (ROOT / "index.md").read_text()]
    missing = []
    for name in ORDER:
        p = ROOT / "briefs" / f"{PACK}{name}.md"
        if not p.exists():
            missing.append(name)
            continue
        parts.append(SEP.format(name=f"briefs/{PACK}{name}.md"))
        parts.append(p.read_text())
    out = ROOT / "llms-full.txt"
    out.write_text("".join(parts))
    print(f"gen_llms_full: {out.name} — {out.stat().st_size:,} bytes, "
          f"{len(ORDER) - len(missing) + 2} sections")
    for m in missing:
        print(f"  ! briefs/{PACK}{m}.md is missing")


if __name__ == "__main__":
    main()
